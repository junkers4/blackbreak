// Assembles src/qcore.wat into src/qcore-bin.js (the binary as base64, so the page works
// from file://). Needs the dev dependency: npm install, then node tools/build-wasm.js.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const watFile = path.join(root, 'src', 'qcore.wat');

const sha = text => crypto.createHash('sha256').update(text).digest('hex');

async function assemble() {
    const wabt = await require('wabt')();
    const text = fs.readFileSync(watFile, 'utf8');
    const mod = wabt.parseWat('qcore.wat', text, {bulk_memory: true});
    mod.validate();
    const {buffer} = mod.toBinary({});
    mod.destroy();
    return {bytes: Buffer.from(buffer), sha: sha(text)};
}

function render({bytes, sha: hash}) {
    return '// Generated by tools/build-wasm.js from src/qcore.wat. Do not edit.\n' +
        'var QQ = globalThis.QQ || (globalThis.QQ = {});\n' +
        `QQ.CORE_WAT_SHA256 = '${hash}';\n` +
        `QQ.CORE_WASM = '${bytes.toString('base64')}';\n`;
}

module.exports = {assemble, render, sha, watFile};
if (require.main === module)
    assemble().then(r => {
        fs.writeFileSync(path.join(root, 'src', 'qcore-bin.js'), render(r));
        console.log(`src/qcore-bin.js written (${r.bytes.length} bytes of WebAssembly)`);
    });
