// Writes docs/REFERENCES.md from src/refs.js: every source, its identifiers, the record
// that confirmed it, and the levels that cite it. Run: node tools/gen-references.js
const fs = require('fs');
const path = require('path');

function build() {
    delete require.cache[require.resolve('../test/load.js')];
    const QQ = require('../test/load.js');
    const usedBy = {};
    const note = (cite, where) => {
        const {key} = QQ.refParts(cite);
        (usedBy[key] = usedBy[key] || new Set()).add(where);
    };
    QQ.LEVELS.forEach((L, i) => {
        const where = `${i + 1} ${L.title}`;
        (L.refs || []).forEach(c => note(c, where));
        L.steps.forEach(s => (s.refs || []).forEach(c => note(c, where)));
    });
    QQ.BOOK.forEach(b => b.refs.forEach(c => note(c, 'gate book')));
    QQ.GLOSSARY.forEach(g => g.refs.forEach(c => note(c, 'glossary')));
    const keys = Object.keys(QQ.REFS).sort((a, b) => QQ.REFS[a].authors.localeCompare(QQ.REFS[b].authors));
    let out = '# Sources\n\nGenerated by `tools/gen-references.js` from `src/refs.js`; do not edit.\n\n' +
        'Every identifier below was checked against the bibliographic record named under "checked" ' +
        '(looked up 2026-10-29). `make check-refs` resolves the DOIs and arXiv ids again online.\n\n';
    for (const k of keys) {
        const r = QQ.REFS[k];
        const ids = [];
        if (r.doi)
            ids.push(`DOI [${r.doi}](https://doi.org/${r.doi})`);
        if (r.arxiv)
            ids.push(`arXiv [${r.arxiv}](https://arxiv.org/abs/${r.arxiv})`);
        if (r.isbn)
            ids.push(`ISBN ${r.isbn}`);
        if (r.url)
            ids.push(`<${r.url}>`);
        out += `- **${k}**: ${QQ.citeText(r)}  \n  ${ids.join(' · ')}  \n  checked: <${r.checked}>  \n` +
            `  cited in: ${[...(usedBy[k] || [])].join('; ')}\n`;
    }
    return out;
}

module.exports = build;
if (require.main === module) {
    fs.writeFileSync(path.join(__dirname, '..', 'docs', 'REFERENCES.md'), build());
    console.log('docs/REFERENCES.md written');
}
